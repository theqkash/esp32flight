const lang_t *L(void)
{
    int l = settings_get()->lang;
    return l == 1 ? &k_pl : l == 2 ? &k_hu : &k_en;
}

const char *lang_weather_desc(int code)
{
    const lang_t *l = L();
    if (code == 0) return l->wx_clear;
    if (code <= 2) return l->wx_partly;
    if (code == 3) return l->wx_overcast;
    if (code == 45 || code == 48) return l->wx_fog;
    if (code >= 51 && code <= 57) return l->wx_drizzle;
    if (code >= 61 && code <= 67) return l->wx_rain;
    if (code >= 71 && code <= 77) return l->wx_snow;
    if (code >= 80 && code <= 82) return l->wx_showers;
    if (code == 85 || code == 86) return l->wx_snow;
    if (code >= 95) return l->wx_thunder;
    return l->wx_overcast;
}

const char *lang_compass(int deg)
{
    static const char *dirs[8] = { "N", "NE", "E", "SE", "S", "SW", "W", "NW" };
    return dirs[((deg % 360) + 382) / 45 % 8];
}

/* METAR weather-group tokens, localized. Order matters: prefixes first. */
const char *lang_metar_wx(const char *code, int lang)
{
    static const struct { const char *c, *en, *pl, *hu; } k[] = {
        { "TS", "thunderstorm", "burza", "zivatar" },
        { "SH", "showers", "przelotnie", "zápor" },
        { "FZ", "freezing", "marznące", "ónos" },
        { "RA", "rain", "deszcz", "eső" },
        { "DZ", "drizzle", "mżawka", "szitálás" },
        { "SN", "snow", "śnieg", "hó" },
        { "GR", "hail", "grad", "jégeső" },
        { "GS", "small hail", "krupa", "hódara" },
        { "FG", "fog", "mgła", "köd" },
        { "BR", "mist", "zamglenie", "pára" },
        { "HZ", "haze", "opar", "szárazköd" },
        { "FU", "smoke", "dym", "füst" },
        { "VC", "nearby", "w pobliżu", "a közelben" },
    };
    for (unsigned i = 0; i < sizeof(k) / sizeof(k[0]); i++) {
        if (strncmp(code, k[i].c, 2) == 0) {
            return lang == 1 ? k[i].pl : lang == 2 ? k[i].hu : k[i].en;
        }
    }
    return NULL;
}
